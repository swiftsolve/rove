/**
 * Write `src/ui/utils/cn-theme.gen.json`: the names cn()'s tailwind-merge
 * config needs, read from the Tailwind theme (rove-tokens' tailwind-theme.css,
 * and the app's own @theme blocks in src/styles/tailwind.css) and rove-tokens'
 * text-styles.css.
 *
 * tailwind-merge only knows a utility's group from these lists. A theme name
 * missing from them isn't recognised, so `cn('text-md', 'text-lg')` keeps both;
 * generating them means a token change can't leave one out.
 *
 *   node scripts/gen/cn-theme.mjs           # rewrite it
 *   node scripts/gen/cn-theme.mjs --check   # fail if it's stale
 */
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const THEME_CSS = join(ROOT, 'src/styles/tailwind.css')
const OUTPUT = join(ROOT, 'src/ui/utils/cn-theme.gen.json')
const require = createRequire(import.meta.url)
// The tokens' theme first, then the app's, as tailwind.css imports them.
const TOKENS_THEME_CSS = require.resolve('@swiftsolve/rove-tokens/tailwind-theme.css')
const TEXT_STYLES_CSS = require.resolve('@swiftsolve/rove-tokens/text-styles.css')
const isCheck = process.argv.includes('--check')

// Colours Tailwind has without a theme entry, listed so they still merge.
const BUILT_IN_COLORS = ['transparent', 'current', 'inherit']
// Longest first, so `--font-weight-*` isn't read as a `--font-*` name.
const NAMESPACES = [
  'font-weight',
  'font',
  'spacing',
  'text',
  'color',
  'leading',
  'tracking',
  'radius',
  'shadow',
  'ease',
  'animate',
]

const rel = (path) => relative(ROOT, path)
const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '')

/** Theme names by namespace, from every `@theme` block: `--text-md` is `text: md`. */
function themeNames(css) {
  const names = Object.fromEntries(NAMESPACES.map((namespace) => [namespace, []]))
  names.color.push(...BUILT_IN_COLORS)
  for (const [, block] of stripComments(css).matchAll(/@theme[^{]*\{([\s\S]*?)\n\}/g)) {
    for (const [, variable] of block.matchAll(/^\s*--([a-z0-9-]+)\s*:/gm)) {
      const namespace = NAMESPACES.find((ns) => variable.startsWith(`${ns}-`))
      if (!namespace) {
        console.error(`The Tailwind theme: --${variable} is in no namespace; add it to NAMESPACES here and to cn.ts`)
        process.exit(1)
      }
      names[namespace].push(variable.slice(namespace.length + 1))
    }
  }
  return names
}

const theme = themeNames(
  (await Promise.all([TOKENS_THEME_CSS, THEME_CSS].map((path) => readFile(path, 'utf8')))).join('\n'),
)
const textStyleClasses = [...(await readFile(TEXT_STYLES_CSS, 'utf8')).matchAll(/^\s*\.(type-[a-z0-9-]+)\s*\{/gm)].map(
  (match) => match[1],
)
const json = `${JSON.stringify(
  {
    $comment:
      "Generated by `npm run gen` from rove-tokens' tailwind-theme.css and text-styles.css, and src/styles/tailwind.css; edit those, not this file.",
    theme,
    textStyleClasses,
  },
  null,
  2,
)}\n`

if (isCheck) {
  const current = await readFile(OUTPUT, 'utf8').catch(() => '')
  if (current !== json) {
    console.error(`${rel(OUTPUT)} is stale: run npm run gen`)
    process.exit(1)
  }
} else {
  await writeFile(OUTPUT, json)
}
const count = Object.values(theme).reduce((sum, names) => sum + names.length, 0)
console.log(
  `cn theme ${isCheck ? 'OK' : 'written'} (${count} names in ${NAMESPACES.length} namespaces, ${textStyleClasses.length} text styles)`,
)
