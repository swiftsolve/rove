/**
 * Write `src/ui/utils/cn-theme.gen.json`: the names cn()'s tailwind-merge
 * config needs, read from the Tailwind theme (rove-tokens' tailwind-theme.css,
 * and the app's own @theme blocks in src/styles/tailwind.css) and rove-tokens'
 * text-styles.css.
 *
 * tailwind-merge only knows a utility's group from these lists. A theme name
 * missing from them isn't recognised, so `cn('text-sm', 'text-lg')` keeps both;
 * generating them means a token change can't leave one out.
 *
 *   node scripts/gen/cn-theme.ts           # rewrite it
 *   node scripts/gen/cn-theme.ts --check   # fail if it's stale
 */
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { schemaProblems } from '../lib/json-schema.ts'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const APP_THEME_CSS = join(ROOT, 'src/styles/tailwind.css')
const OUTPUT = join(ROOT, 'src/ui/utils/cn-theme.gen.json')
const OUTPUT_SCHEMA = join(ROOT, 'schemas/cn-theme.schema.json')
const require = createRequire(import.meta.url)
// The tokens' theme first, then the app's, as tailwind.css imports them.
const TOKENS_THEME_CSS = require.resolve('@swiftsolve/rove-tokens/tailwind-theme.css')
const TEXT_STYLES_CSS = require.resolve('@swiftsolve/rove-tokens/text-styles.css')
const isCheck = process.argv.includes('--check')

// Colours Tailwind has without a theme entry, listed so they still merge.
const BUILT_IN_COLORS = ['transparent', 'current', 'inherit']
// Longest first, so `--font-weight-*` isn't read as a `--font-*` name.
const NAMESPACES = [
  'font-weight',
  'font',
  'spacing',
  'text',
  'color',
  'leading',
  'tracking',
  'radius',
  'shadow',
  'ease',
  'animate',
]

const relativeToRoot = (path: string) => relative(ROOT, path)
const stripComments = (css: string) => css.replace(/\/\*[\s\S]*?\*\//g, '')

/** Theme names by namespace, from every `@theme` block: `--text-sm` is `text: sm`. */
function themeNames(css: string): Record<string, string[]> {
  const names = new Map(NAMESPACES.map((namespace) => [namespace, namespace === 'color' ? [...BUILT_IN_COLORS] : []]))
  for (const [, block = ''] of stripComments(css).matchAll(/@theme[^{]*\{([\s\S]*?)\n\}/g)) {
    for (const [, variable = ''] of block.matchAll(/^\s*--([a-z0-9-]+)\s*:/gm)) {
      const namespace = NAMESPACES.find((ns) => variable.startsWith(`${ns}-`))
      if (!namespace) {
        console.error(`The Tailwind theme: --${variable} is in no namespace; add it to NAMESPACES here and to cn.ts`)
        process.exit(1)
      }
      names.get(namespace)?.push(variable.slice(namespace.length + 1))
    }
  }
  return Object.fromEntries(names)
}

const themeCss = await Promise.all([TOKENS_THEME_CSS, APP_THEME_CSS].map((path) => readFile(path, 'utf8')))
const theme = themeNames(themeCss.join('\n'))
const textStylesCss = await readFile(TEXT_STYLES_CSS, 'utf8')
const textStyleClasses = [...textStylesCss.matchAll(/^\s*\.(type-[a-z0-9-]+)\s*\{/gm)].map((match) => match[1])
const output = {
  $schema: '../../../schemas/cn-theme.schema.json',
  $comment:
    "Generated by `npm run gen` from rove-tokens' tailwind-theme.css and text-styles.css, and src/styles/tailwind.css; edit those, not this file.",
  tailwindThemeNames: theme,
  textStyleClasses,
}
const outputSchemaProblems = await schemaProblems(OUTPUT_SCHEMA, output, relativeToRoot(OUTPUT))
if (outputSchemaProblems.length > 0) {
  console.error(outputSchemaProblems.join('\n'))
  process.exit(1)
}
const outputJson = `${JSON.stringify(output, null, 2)}\n`

if (isCheck) {
  const current = await readFile(OUTPUT, 'utf8').catch(() => '')
  if (current !== outputJson) {
    console.error(`${relativeToRoot(OUTPUT)} is stale: run npm run gen`)
    process.exit(1)
  }
} else {
  await writeFile(OUTPUT, outputJson)
}
const nameCount = Object.values(theme).reduce((sum, names) => sum + names.length, 0)
console.log(
  `cn theme ${isCheck ? 'OK' : 'written'} (${nameCount} names in ${NAMESPACES.length} namespaces, ${textStyleClasses.length} text styles)`,
)
